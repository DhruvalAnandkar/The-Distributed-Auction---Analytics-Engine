'use strict';

const fs = require('fs');
const path = require('path');
const { GoogleGenerativeAI } = require('@google/generative-ai');

const ROOT_DIR = path.resolve(__dirname, '..');
const API_DIR = path.join(ROOT_DIR, 'apps', 'api');
const TODO_FILE = path.join(ROOT_DIR, 'TODO.md');
const MODEL_NAME = 'gemini-3.8-flash';
const MAX_RETRIES = 5;
const INITIAL_BACKOFF_MS = 1000;
const SOURCE_EXTENSIONS = new Set(['.js', '.ts']);
const TODO_COMMENT_RE = /\/\/\s*(TODO|FIXME)\b(.*)$/;
const PROMPT =
  'You are an expert enterprise backend engineer. Add professional JSDoc comments to all functions, classes, and complex logic in this code. Return ONLY the raw code, without any markdown formatting, backticks, or explanations.';

function collectSourceFiles(directory, files = []) {
  let entries;

  try {
    entries = fs.readdirSync(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') {
      return files;
    }
    throw error;
  }

  for (const entry of entries) {
    if (entry.name === 'node_modules' || entry.name === '.git') {
      continue;
    }

    const fullPath = path.join(directory, entry.name);

    if (entry.isSymbolicLink()) {
      continue;
    }

    if (entry.isDirectory()) {
      collectSourceFiles(fullPath, files);
      continue;
    }

    if (entry.isFile() && SOURCE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      files.push(fullPath);
    }
  }

  return files;
}

function isInsideNodeModules(filePath) {
  return filePath.split(path.sep).includes('node_modules');
}

function stripMarkdownFences(text) {
  const trimmed = String(text || '').trim();
  const fenced = trimmed.match(/^```(?:javascript|js)?\s*\r?\n([\s\S]*?)\r?\n```$/i);
  if (fenced) {
    return fenced[1];
  }

  return trimmed.replace(/^```(?:javascript|js)?\s*/i, '').replace(/\s*```$/i, '');
}

function toPosixPath(filePath) {
  return path.relative(ROOT_DIR, filePath).split(path.sep).join('/');
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function isServiceUnavailable(error) {
  const status = error && (error.status || error.statusCode);
  const message = String((error && error.message) || '');
  const statusText = String((error && error.statusText) || '');

  return (
    status === 503 ||
    /503/.test(message) ||
    /service unavailable/i.test(message) ||
    /service unavailable/i.test(statusText)
  );
}

function isFetchError(error) {
  const name = error && (error.name || (error.constructor && error.constructor.name));
  const message = String((error && error.message) || '');
  const status = error && (error.status || error.statusCode);

  return (
    name === 'GoogleGenerativeAIFetchError' ||
    /fetch/i.test(String(name || '')) ||
    /fetch/i.test(message) ||
    typeof status === 'number'
  );
}

function isRetryableApiError(error) {
  if (isServiceUnavailable(error)) {
    return true;
  }

  if (!isFetchError(error)) {
    return false;
  }

  const status = error && (error.status || error.statusCode);
  return status == null || status >= 500;
}

function isFallbackError(error) {
  return isServiceUnavailable(error) || isFetchError(error);
}

async function generateContentWithBackoff(model, prompt) {
  let delayMs = INITIAL_BACKOFF_MS;
  let lastError;

  for (let attempt = 0; attempt <= MAX_RETRIES; attempt += 1) {
    try {
      return await model.generateContent(prompt);
    } catch (error) {
      lastError = error;

      if (!isRetryableApiError(error) || attempt === MAX_RETRIES) {
        break;
      }

      console.warn(
        `Gemini API unavailable. Waiting ${delayMs}ms before retry ${attempt + 1}/${MAX_RETRIES}...`
      );
      await sleep(delayMs);
      delayMs *= 2;
    }
  }

  throw lastError;
}

function collectTodoComments() {
  const files = collectSourceFiles(API_DIR).filter((filePath) => !isInsideNodeModules(filePath));
  const items = [];

  for (const filePath of files) {
    const contents = fs.readFileSync(filePath, 'utf8');
    const lines = contents.split(/\r?\n/);

    lines.forEach((line, index) => {
      const match = line.match(TODO_COMMENT_RE);
      if (!match) {
        return;
      }

      items.push({
        file: toPosixPath(filePath),
        line: index + 1,
        kind: match[1].toUpperCase(),
        text: line.trim(),
      });
    });
  }

  return items;
}

function writeTodoFallback() {
  const items = collectTodoComments();
  const generatedAt = new Date().toISOString();
  const lines = [
    '# Open TODOs and FIXMEs',
    '',
    `_Generated by \`scripts/auto-documenter.js\` after the Gemini API became unavailable._`,
    '',
    `Last scanned: ${generatedAt}`,
    '',
  ];

  if (items.length === 0) {
    lines.push('No `// TODO` or `// FIXME` comments were found under `apps/api`.');
    lines.push('');
  } else {
    let currentFile = '';
    for (const item of items) {
      if (item.file !== currentFile) {
        if (currentFile) {
          lines.push('');
        }
        currentFile = item.file;
        lines.push(`## \`${item.file}\``);
        lines.push('');
      }

      lines.push(`- Line ${item.line} (${item.kind}): \`${item.text}\``);
    }
    lines.push('');
  }

  fs.writeFileSync(TODO_FILE, lines.join('\n'), 'utf8');
  console.log('Wrote fallback task list to TODO.md');
}

async function documentRandomApiFile() {
  const undocumentedFiles = collectSourceFiles(API_DIR).filter((filePath) => {
    if (isInsideNodeModules(filePath) || path.extname(filePath).toLowerCase() !== '.js') {
      return false;
    }

    const contents = fs.readFileSync(filePath, 'utf8');
    return !contents.includes('/**');
  });

  if (undocumentedFiles.length === 0) {
    console.log('No undocumented JavaScript files found.');
    return;
  }

  const selectedFile = undocumentedFiles[Math.floor(Math.random() * undocumentedFiles.length)];
  const originalSource = fs.readFileSync(selectedFile, 'utf8');

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error('GEMINI_API_KEY is not set.');
  }

  const genAI = new GoogleGenerativeAI(apiKey);
  const model = genAI.getGenerativeModel({ model: MODEL_NAME });
  const result = await generateContentWithBackoff(
    model,
    `${PROMPT}\n\n${originalSource}`
  );
  const documentedSource = stripMarkdownFences(result.response.text());

  if (!documentedSource.trim()) {
    throw new Error(`Gemini returned an empty response for ${toPosixPath(selectedFile)}`);
  }

  const output = documentedSource.endsWith('\n') ? documentedSource : `${documentedSource}\n`;
  fs.writeFileSync(selectedFile, output, 'utf8');

  console.log(toPosixPath(selectedFile));
}

async function main() {
  try {
    await documentRandomApiFile();
  } catch (error) {
    if (isFallbackError(error)) {
      console.warn(
        'Gemini API failed after retries (503 or fetch error). Running TODO fallback instead.'
      );
      console.warn(error);
    } else {
      console.warn('Autonomous documenter encountered an error. Running TODO fallback instead.');
      console.warn(error);
    }

    writeTodoFallback();
  }
}

main()
  .catch((error) => {
    console.warn('Autonomous documenter failed unexpectedly. Running TODO fallback instead.');
    console.warn(error);
    try {
      writeTodoFallback();
    } catch (fallbackError) {
      console.warn('Failed to write TODO.md fallback:', fallbackError);
    }
  })
  .finally(() => {
    process.exit(0);
  });
